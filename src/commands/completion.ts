/**
 * venus completion 命令。
 *
 * 安装/卸载 shell 补全（bash + PowerShell）：
 *   bash        → ~/.venus-completion.sh + .bashrc 标记块 source
 *   powershell  → profile 目录 VenusCompletion.ps1 + $PROFILE 标记块 dot-source
 *
 * 采用 OpenSpec 同款模式：
 *   - 补全脚本是静态生成的（命令面固定，无动态数据源）
 *   - rc/profile 中的配置用 START/END 标记块包裹，卸载时只删标记块
 */

import * as fs from 'node:fs';
import * as os from 'node:os';
import * as path from 'node:path';

/** 支持的 shell */
export type CompletionShell = 'bash' | 'powershell';

/** completion 命令选项 */
export interface CompletionOptions {
    /** 目标 shell（省略时全部） */
    shell?: string;
}

/** 标记块（rc/profile 中由 venus 管理的区段） */
export const COMPLETION_MARKERS = {
    start: '# VENUS-COMPLETION:START',
    end: '# VENUS-COMPLETION:END',
};

/**
 * 顶层命令定义（静态补全数据源）。
 * 新增 CLI 命令时同步更新此表。
 * subcommands 非空的命令为嵌套子命令组（补全第二级）。
 */
const VENUS_COMMANDS: { name: string; description: string; flags: string[]; subcommands?: string[] }[] = [
    { name: 'init', description: '生成全部技能与指令到当前项目', flags: ['--tools', '--force'] },
    { name: 'list', description: '列出已安装技能', flags: ['--json'] },
    { name: 'validate', description: '校验技能规范符合性', flags: ['--json'] },
    { name: 'update', description: '更新技能到最新版', flags: ['--force'] },
    {
        name: 'generate',
        description: '按类型生成新技能骨架',
        flags: ['--type', '--name', '--desc', '--force'],
    },
    {
        name: 'spec',
        description: '规格驱动工作流（new/status/instructions/archive）',
        flags: [],
        subcommands: ['new', 'status', 'instructions', 'archive'],
    },
];

/** 校验 shell 参数 */
export function isCompletionShell(value: string): value is CompletionShell {
    return value === 'bash' || value === 'powershell';
}

/** 生成 bash 补全脚本（compgen + complete 模式） */
export function generateBashCompletion(): string {
    const commandList = VENUS_COMMANDS.map((c) => c.name).join(' ');
    const caseBlocks = VENUS_COMMANDS.map((cmd) => {
        const flags = cmd.flags.join(' ');
        // 嵌套子命令组：第二级补全子命令名；普通命令：仅 flags
        const tail =
            cmd.subcommands === undefined
                ? '      fi\n      ;;'
                : `      elif [[ $COMP_CWORD -eq 2 ]]; then
        COMPREPLY=($(compgen -W "${cmd.subcommands.join(' ')}" -- "$cur"))
      fi
      ;;`;
        return `    ${cmd.name})
      if [[ $cur == -* ]]; then
        COMPREPLY=($(compgen -W "${flags}" -- "$cur"))
${tail}`;
    }).join('\n');

    return `# Bash completion script for venus CLI
# Auto-generated by venus completion install - do not edit manually

_venus_completion() {
  local cur
  COMPREPLY=()
  cur="\${COMP_WORDS[COMP_CWORD]}"
  local cmd="\${COMP_WORDS[1]}"

  if [[ $COMP_CWORD -eq 1 ]]; then
    local commands="${commandList}"
    COMPREPLY=($(compgen -W "$commands" -- "$cur"))
    return 0
  fi

  case "$cmd" in
${caseBlocks}
  esac
  return 0
}

complete -F _venus_completion venus
`;
}

/** 生成 PowerShell 补全脚本（Register-ArgumentCompleter 模式） */
export function generatePowerShellCompletion(): string {
    const commandEntries = VENUS_COMMANDS.map(
        (c) => `    [System.Management.Automation.CompletionResult]::new("${c.name}", "${c.name}", "ParameterValue", "${c.description}")`
    ).join('\n');

    const flagSwitchCases = VENUS_COMMANDS.map((cmd) => {
        const flagList = cmd.flags.map((f) => `"${f}"`).join(', ');
        // 嵌套子命令组：第二级补全子命令名
        const subcommandBlock =
            cmd.subcommands === undefined
                ? ''
                : `            elseif ($commandCount -eq 2 -or ($commandCount -eq 3 -and $wordToComplete)) {
                @(${cmd.subcommands.map((s) => `'${s}'`).join(', ')}) | Where-Object { $_ -like "$wordToComplete*" } | ForEach-Object {
                    [System.Management.Automation.CompletionResult]::new($_, $_, "ParameterValue", "${cmd.description}")
                }
            }`;
        return `        '${cmd.name}' {
            if ($wordToComplete -like '-*') {
                $flags = @(${flagList})
                $flags | Where-Object { $_ -like "$wordToComplete*" } | ForEach-Object {
                    [System.Management.Automation.CompletionResult]::new($_, $_, "ParameterName", "")
                }
                return
            }${subcommandBlock}
        }`;
    }).join('\n');

    return `# PowerShell completion script for venus CLI
# Auto-generated by venus completion install - do not edit manually

$venusCompleter = {
    param($wordToComplete, $commandAst, $cursorPosition)

    $tokens = $commandAst.ToString() -split '\\s+'
    $commandCount = ($tokens | Measure-Object).Count

    # Top-level commands
    if ($commandCount -eq 1 -or ($commandCount -eq 2 -and $wordToComplete)) {
${commandEntries}
        return
    }

    $command = $tokens[1]
    switch ($command) {
${flagSwitchCases}
    }
}

Register-ArgumentCompleter -CommandName venus -ScriptBlock $venusCompleter
`;
}

/** 安装/卸载结果 */
export interface CompletionActionResult {
    shell: CompletionShell;
    /** 补全脚本路径 */
    scriptPath: string;
    /** rc/profile 路径 */
    rcPath: string;
    action: 'installed' | 'already-installed' | 'removed' | 'not-installed';
}

/** bash 安装路径：~/.venus-completion.sh */
function bashScriptPath(): string {
    return path.join(os.homedir(), '.venus-completion.sh');
}

/** bash rc 路径：~/.bashrc */
function bashRcPath(): string {
    return path.join(os.homedir(), '.bashrc');
}

/** PowerShell 脚本路径：profile 目录下 VenusCompletion.ps1 */
function powerShellScriptPath(): string {
    return path.join(powerShellProfileDir(), 'VenusCompletion.ps1');
}

/** PowerShell profile 目录（Documents/PowerShell，不存在则回退 WindowsPowerShell） */
function powerShellProfileDir(): string {
    const home = os.homedir();
    const core = path.join(home, 'Documents', 'PowerShell');
    if (fs.existsSync(core)) {
        return core;
    }
    return path.join(home, 'Documents', 'WindowsPowerShell');
}

/** 在 rc 内容中追加/替换标记块 */
function upsertMarkerBlock(content: string, block: string): string {
    const removed = removeMarkerBlock(content);
    const trimmed = removed.trimEnd();
    return `${trimmed}${trimmed ? '\n\n' : ''}${block}\n`;
}

/** 从 rc 内容中删除标记块（含块前后的空行规整） */
function removeMarkerBlock(content: string): string {
    const startIdx = content.indexOf(COMPLETION_MARKERS.start);
    if (startIdx === -1) {
        return content;
    }
    const endIdx = content.indexOf(COMPLETION_MARKERS.end, startIdx);
    if (endIdx === -1) {
        return content;
    }
    // 删除从 START 行首到 END 行尾（含换行）
    const before = content.slice(0, startIdx);
    const after = content.slice(endIdx + COMPLETION_MARKERS.end.length).replace(/^\r?\n/, '');
    return before + after;
}

/** 安装单个 shell 的补全 */
function installShell(shell: CompletionShell): CompletionActionResult {
    if (shell === 'bash') {
        const scriptPath = bashScriptPath();
        const rcPath = bashRcPath();
        const script = generateBashCompletion();
        const block = [
            COMPLETION_MARKERS.start,
            '# Venus CLI 补全（由 venus completion install 管理，勿手工编辑）',
            `if [ -f "${scriptPath.replaceAll('\\', '/')}" ]; then`,
            `    . "${scriptPath.replaceAll('\\', '/')}"`,
            'fi',
            COMPLETION_MARKERS.end,
        ].join('\n');

        fs.writeFileSync(scriptPath, script, 'utf8');
        const rcContent = fs.existsSync(rcPath) ? fs.readFileSync(rcPath, 'utf8') : '';
        if (rcContent.includes(COMPLETION_MARKERS.start)) {
            // 已有标记块：替换为最新（幂等升级）
            fs.writeFileSync(rcPath, upsertMarkerBlock(rcContent, block), 'utf8');
            return { shell, scriptPath, rcPath, action: 'already-installed' };
        }
        fs.writeFileSync(rcPath, upsertMarkerBlock(rcContent, block), 'utf8');
        return { shell, scriptPath, rcPath, action: 'installed' };
    }

    // powershell
    const scriptPath = powerShellScriptPath();
    const rcPath = path.join(powerShellProfileDir(), 'Microsoft.PowerShell_profile.ps1');
    const script = generatePowerShellCompletion();
    const block = [
        COMPLETION_MARKERS.start,
        '# Venus CLI 补全（由 venus completion install 管理，勿手工编辑）',
        `if (Test-Path "${scriptPath.replaceAll('\\', '\\\\')}") {`,
        `    . "${scriptPath.replaceAll('\\', '\\\\')}"`,
        '}',
        COMPLETION_MARKERS.end,
    ].join('\n');

    fs.mkdirSync(path.dirname(scriptPath), { recursive: true });
    fs.writeFileSync(scriptPath, script, 'utf8');
    const profileContent = fs.existsSync(rcPath) ? fs.readFileSync(rcPath, 'utf8') : '';
    if (profileContent.includes(COMPLETION_MARKERS.start)) {
        fs.writeFileSync(rcPath, upsertMarkerBlock(profileContent, block), 'utf8');
        return { shell, scriptPath, rcPath, action: 'already-installed' };
    }
    fs.writeFileSync(rcPath, upsertMarkerBlock(profileContent, block), 'utf8');
    return { shell, scriptPath, rcPath, action: 'installed' };
}

/** 卸载单个 shell 的补全（只删标记块与脚本文件，不动其他配置） */
function uninstallShell(shell: CompletionShell): CompletionActionResult {
    if (shell === 'bash') {
        const scriptPath = bashScriptPath();
        const rcPath = bashRcPath();
        if (fs.existsSync(rcPath)) {
            const rcContent = fs.readFileSync(rcPath, 'utf8');
            if (rcContent.includes(COMPLETION_MARKERS.start)) {
                fs.writeFileSync(rcPath, removeMarkerBlock(rcContent), 'utf8');
            }
        }
        if (fs.existsSync(scriptPath)) {
            fs.rmSync(scriptPath);
        }
        return { shell, scriptPath, rcPath, action: 'removed' };
    }

    const scriptPath = powerShellScriptPath();
    const rcPath = path.join(powerShellProfileDir(), 'Microsoft.PowerShell_profile.ps1');
    if (fs.existsSync(rcPath)) {
        const profileContent = fs.readFileSync(rcPath, 'utf8');
        if (profileContent.includes(COMPLETION_MARKERS.start)) {
            fs.writeFileSync(rcPath, removeMarkerBlock(profileContent), 'utf8');
        }
    }
    if (fs.existsSync(scriptPath)) {
        fs.rmSync(scriptPath);
    }
    return { shell, scriptPath, rcPath, action: 'removed' };
}

/**
 * 执行 install / uninstall。
 *
 * @param action - install 或 uninstall
 * @param options - 命令选项
 */
export function runCompletion(action: 'install' | 'uninstall', options: CompletionOptions): CompletionActionResult[] {
    const shells: CompletionShell[] = options.shell && isCompletionShell(options.shell)
        ? [options.shell]
        : ['bash', 'powershell'];
    if (options.shell && !isCompletionShell(options.shell)) {
        throw new Error(`未知的 shell：${options.shell}（可选：bash, powershell）`);
    }
    return shells.map((shell) =>
        action === 'install' ? installShell(shell) : uninstallShell(shell)
    );
}

/** 输出结果文本 */
export function renderCompletionOutput(results: CompletionActionResult[], action: 'install' | 'uninstall'): string {
    const lines: string[] = [];
    for (const r of results) {
        if (action === 'install') {
            const state = r.action === 'already-installed' ? '已安装，已刷新' : '安装完成';
            lines.push(`[${r.shell}] ${state}`);
            lines.push(`  补全脚本：${r.scriptPath}`);
            lines.push(`  生效配置：${r.rcPath}`);
            lines.push(r.shell === 'bash' ? '  新开终端或 source ~/.bashrc 后生效' : '  新开 PowerShell 窗口后生效');
        } else {
            lines.push(`[${r.shell}] 已卸载（清理 ${r.rcPath} 中的标记块）`);
        }
    }
    return lines.join('\n');
}
